// Copies step7/OB1.awl into step7/ob1.js so index.html also works when opened
// straight from disk (browsers block fetch() on file://).  Run: node tools/embed.js
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "step7");
const src = fs.readFileSync(path.join(dir, "OB1.awl"), "utf8").replace(/\r\n/g, "\n");
fs.writeFileSync(path.join(dir, "ob1.js"), "// Generated by tools/embed.js from OB1.awl. Do not edit by hand.\nwindow.OB1_SOURCE = " + JSON.stringify(src) + ";\n");
console.log("step7/ob1.js updated");
